// Builds everything that gets published into dist/:
//   widget.js        the browser widget: one minified script
//   server/…         the server (ESM and CJS, with types)
//   shared/…         the types the widget and server share
//
// The widget's source is also written to src/server/widget-source.generated.ts,
// so the server can serve it itself. `--widget-only` stops after that step
// (it's all tests and typechecking need).
import { build as bundle } from "esbuild";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { widgetOptions } from "./widget-options.ts";

const widgetOnly = process.argv.includes("--widget-only");

if (!widgetOnly) rmSync("dist", { recursive: true, force: true });
mkdirSync("dist", { recursive: true });

const widget = await bundle({ ...widgetOptions, minify: true, write: false });
const widgetCode = widget.outputFiles[0]!.text;
writeFileSync("dist/widget.js", widgetCode);
writeFileSync(
  "src/server/widget-source.generated.ts",
  `// generated by scripts/build.ts: do not edit\nexport const widgetSource: string = ${JSON.stringify(widgetCode)};\n`,
);
console.log(`widget.js ${(widgetCode.length / 1024).toFixed(0)}kB`);

if (!widgetOnly) {
  const { build } = await import("tsup");
  await build({
    entry: {
      "server/index": "src/server/index.ts",
      "server/slack": "src/server/slack.ts",
      "shared/index": "src/shared/index.ts",
    },
    outDir: "dist",
    format: ["esm", "cjs"],
    // (tsup's declaration bundler sets `baseUrl`, which TypeScript 6 deprecates)
    dts: { compilerOptions: { ignoreDeprecations: "6.0" } },
    platform: "neutral",
    target: "es2022",
    // runtime dependencies stay dependencies
    external: ["octokit", "zod"],
    splitting: false,
    sourcemap: false,
    clean: false,
  });
}
